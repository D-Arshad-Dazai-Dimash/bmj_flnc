namespace Barnamaj.API.Entities;

/// <summary>
/// Уровень подтверждения личности пользователя (рынок РК).
///
/// Двухуровневая модель в соответствии с законом РК «О ПОД/ФТ» №191-IV:
///   None        — не верифицирован, доступ только к публичным разделам.
///   Lite        — телефон (+7) + ИИН подтверждены: разрешает создание профиля,
///                 чат, заявки на проекты.
///   DocPending  — документ + селфи загружены, ожидают модерации.
///   Full        — модератор/провайдер подтвердил документ: разрешены денежные
///                 операции (эскроу, выплаты).
///   Rejected    — документ отклонён, требуется повторная загрузка.
///
/// Переходы валидируются в KycService: повышать уровень можно только последовательно.
/// </summary>
public enum KycStatus : byte
{
    None       = 0,
    Lite       = 1,
    DocPending = 2,
    Full       = 3,
    Rejected   = 4,
}
